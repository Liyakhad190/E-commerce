/**
 * Reusable product lookup – supports both 'prod-1' and raw numeric '1' formats.
 */
export function getProductById(id) {
  if (!id) return null;
  const cleanId = String(id).trim().toLowerCase();

  const directMatch = GROCERY_ITEMS.find((p) => String(p.id).toLowerCase() === cleanId);
  if (directMatch) return directMatch;

  const numSuffixMatch = GROCERY_ITEMS.find((p) => {
    const rawNum = String(p.id).replace(/\D/g, '');
    const searchNum = cleanId.replace(/\D/g, '');
    return rawNum && searchNum && rawNum === searchNum;
  });
  return numSuffixMatch || null;
}

/**
 * Reusable category lookup by slug.
 */
export function getCategoryBySlug(slug) {
  if (!slug) return null;
  return CATEGORIES.find((c) => c.id.toLowerCase() === String(slug).trim().toLowerCase()) || null;
}

